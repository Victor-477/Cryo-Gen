#!/usr/bin/env python3
"""Height maps, cliff and gravel textures and .terrain files for the two example games.

    python3 tools/make_terrains.py     (also run at the end of make_ashen_assets.py and
                                        make_outpost_assets.py)

Ashen Keep: low mounds inside the outer bailey, and wooded hills and crags rising around the
castle. Outpost Kestrel: the compound sits in a rocky basin ringed by ridges. The play areas
keep their floors; the terrain lies just under them.
"""
import math, os
import numpy as np
from PIL import Image
import make_ashen_assets as A
from make_ashen_assets import fbm, relief, grey

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "crates", "cryo-editor")
N = 257   # samples a side

def grid(size, center):
    t = np.linspace(-size / 2, size / 2, N)
    z, x = np.meshgrid(t + center[1], t + center[0], indexing="ij")   # rows run along +Z
    return x, z

def box_distance(x, z, x0, x1, z0, z1):
    dx = np.maximum(np.maximum(x0 - x, x - x1), 0)
    dz = np.maximum(np.maximum(z0 - z, z - z1), 0)
    return np.hypot(dx, dz)

def ridges(seed, scale):
    """Sharp-crested mountain noise, 0..1."""
    n = fbm(N, seed, (2, 4, 8, 16))
    r = 1 - np.abs(fbm(N, seed + 1, (3, 6, 12)) * 2 - 1)
    return (n * 0.6 + r * r * 0.4) ** 1.2 * scale

def smooth(a, b, v):
    t = np.clip((v - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)

def save(out, name, h, base, height, size, center, tex, tile, steep_tex, steep_tile, steep, color=(1, 1, 1)):
    v = np.clip((h - base) / height, 0, 1)
    Image.fromarray((v * 65535).astype(np.uint16)).save(os.path.join(out, f"{name}_height.png"))
    with open(os.path.join(out, f"{name}.terrain"), "w") as f:
        f.write(f"# Generated by tools/make_terrains.py\nheightmap = {name}_height.png\nsize = {size} {size}\n"
                f"height = {height}\nbase = {base}\ntexture = {tex}\ntile = {tile}\nsteep_texture = {steep_tex}\n"
                f"steep_tile = {steep_tile}\nsteep = {steep}\ncolor = {color[0]} {color[1]} {color[2]}\nroughness = 0.92\n")
    # the height the games read back to stand things on the ground: same grid, same numbers
    return v * height + base

def cliff_texture(name, seed, tint):
    S = 1024
    y, x = np.mgrid[0:S, 0:S] / S
    strata = np.sin((y * 9 + fbm(S, seed, (2, 4, 8)) * 1.5) * math.tau) * 0.5 + 0.5
    cracks = np.clip(1 - np.abs(fbm(S, seed + 3, (4, 8, 16, 32)) - 0.5) * 30, 0, 1)
    grain = fbm(S, seed + 5, (32, 64, 128, 256))
    lichen = np.clip((fbm(S, seed + 7, (6, 12, 24)) - 0.62) * 5, 0, 1)[..., None]
    v = 0.45 + strata * 0.12 + (grain - 0.5) * 0.3 - cracks * 0.3
    col = grey(v * relief(strata * 0.8 + grain * 0.6 - cracks * 1.2, 1.4), tint)
    A.save_texture(name, col * (1 - lichen * 0.5) + np.array([0.3, 0.33, 0.2]) * lichen * 0.5)

def gravel_texture(name, seed):
    S = 1024
    pebbles = fbm(S, seed, (64, 128, 256))
    stones = np.clip((fbm(S, seed + 2, (24, 48, 96)) - 0.55) * 5, 0, 1)
    dirt = fbm(S, seed + 4, (2, 4, 8, 16))
    tufts = np.clip((fbm(S, seed + 6, (8, 16, 32)) - 0.7) * 5, 0, 1)[..., None]
    v = 0.32 + (pebbles - 0.5) * 0.25 + stones * 0.18 + (dirt - 0.5) * 0.15
    col = grey(v * relief(pebbles * 0.8 + stones, 1.2), (1.0, 0.94, 0.85))
    A.save_texture(name, col * (1 - tufts * 0.6) + np.array([0.2, 0.22, 0.13]) * tufts * 0.6)

def ashen(out):
    A.OUT = out
    cliff_texture("tex_cliff.jpg", 401, (0.92, 0.92, 0.95))
    size, center = 280.0, (0.0, -5.0)
    x, z = grid(size, center)
    # inside the bailey: soft mounds away from the paths the fights use
    h = np.zeros_like(x)
    for bx, bz, r, top in [(-14, 47, 6.0, 1.4), (14, 31, 5.0, 1.0), (-13.5, 17, 5.0, 1.1), (14, 50, 4.5, 0.9),
                           (-15, 36, 4.0, 0.7), (12, 12, 4.0, 0.6), (-4, 40, 7.0, 0.35), (6, 22, 6.0, 0.3)]:
        h += top * np.exp(-((x - bx) ** 2 + (z - bz) ** 2) / (2 * (r / 2) ** 2))
    h += (fbm(N, 411, (8, 16, 32)) - 0.5) * 0.25
    bailey = box_distance(x, z, -19.5, 19.5, 2.5, 56.5) == 0
    keep = np.minimum(box_distance(x, z, -21, 21, 1, 58.5), box_distance(x, z, -20, 20, -70, 2))
    inner_court = box_distance(x, z, -20, 20, -70, 1.5) == 0
    # outside the walls: slopes rising to wooded hills, crags further off
    d = keep
    hills = -0.4 + smooth(1.5, 50, d) ** 1.4 * 24 + ridges(421, 18) * smooth(8, 70, d) + (fbm(N, 431, (16, 32)) - 0.5) * 1.2 * smooth(1, 6, d)
    h = np.where(bailey, np.maximum(h, 0.0), np.where(inner_court, -0.4, hills))
    hv = save(out, "keep", h, -1.0, 52.0, size, center, "tex_grass.jpg", 6, "tex_cliff.jpg", 10, 0.82)
    return hv

def outpost(out):
    A.OUT = out
    cliff_texture("tex_cliff.jpg", 501, (0.85, 0.85, 0.82))
    gravel_texture("tex_gravel.jpg", 511)
    size, center = 320.0, (0.0, -6.0)
    x, z = grid(size, center)
    d = np.minimum(box_distance(x, z, -27, 27, 1.5, 47.5), box_distance(x, z, -17, 17, -59, 3))
    basin = -0.3 + smooth(1.0, 30, d) * 3.0 + (fbm(N, 521, (16, 32, 64)) - 0.5) * 0.8 * smooth(1, 5, d)
    mountains = smooth(35, 140, d) ** 1.3 * 46 + ridges(531, 26) * smooth(25, 110, d)
    h = np.where(d == 0, -0.3, basin + mountains)
    hv = save(out, "basin", h, -1.0, 80.0, size, center, "tex_gravel.jpg", 7, "tex_cliff.jpg", 12, 0.8, (0.85, 0.85, 0.85))
    return hv

def write_file_list(game):
    out = os.path.join(SRC, "template", game)
    files = sorted(os.listdir(out))
    script = "make_ashen_assets.py" if game == "ashen" else "make_outpost_assets.py"
    rs = f"// Generated by tools/{script}. Do not edit.\npub const FILES: &[(&str, &[u8])] = &[\n"
    rs += "".join(f'    ("{f}", include_bytes!("../template/{game}/{f}")),\n' for f in files) + "];\n"
    open(os.path.join(SRC, "src", f"{game}_files.rs"), "w").write(rs)

if __name__ == "__main__":
    ashen(os.path.join(SRC, "template", "ashen"))
    outpost(os.path.join(SRC, "template", "outpost"))
    write_file_list("ashen")
    write_file_list("outpost")
    print("terrains written")
